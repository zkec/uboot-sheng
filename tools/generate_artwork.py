"""Generate fixed, antialiased menu labels and icon alpha masks, without fonts at boot."""
from pathlib import Path
import io
import re
import struct
import subprocess
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'assets'
import argparse
p=argparse.ArgumentParser();p.add_argument('--font',required=True);args=p.parse_args()
FONT = args.font
labels = dict(title=('Choose your system', 38),
              android=('Android', 38), linux=('Linux', 38),
              selected=('SELECTED', 12), choose=('VOLUME UP / DOWN', 15),
              choose_sub=('Choose', 15), confirm=('POWER', 15),
              confirm_sub=('Select', 15), restart=('Restart',18),
              bootloader=('Bootloader',18), poweroff=('Power off',18),
              slotswitch=('Switch slot',18),
              action_failed=('Action failed. Choose another option.',13))
assets = {}
for name, (text, size) in labels.items():
    font = ImageFont.truetype(FONT, size*2)
    box = font.getbbox(text)
    image = Image.new('L', (box[2]-box[0]+4, box[3]-box[1]+4))
    ImageDraw.Draw(image).text((2-box[0], 2-box[1]), text, fill=255, font=font)
    assets[name] = image
# Established brand silhouettes share one icon frame, without custom cartoon
# proportions. Center the head-only Android mark within the same frame as Tux.
for name,filename in [('android_icon','android-simple.svg')]:
    png=subprocess.check_output(['rsvg-convert','-w','492','-h','492',str(OUT/filename)])
    mask=Image.open(io.BytesIO(png)).getchannel('A')
    mask=mask.crop(mask.getbbox());mask.thumbnail((246,246),Image.Resampling.LANCZOS)
    frame=Image.new('L',(246,246));frame.paste(mask,((246-mask.width)//2,(246-mask.height)//2))
    assets[name]=frame
header=['/* SPDX-License-Identifier: GPL-2.0-or-later */',
        '/* Generated by generate_artwork.py. Icon credits: ARTWORK.txt. */',
        'struct menu_art { int w, h; const unsigned char *data; unsigned int bytes; };']
for name, image in assets.items():
    raw=image.tobytes(); packed=bytearray();pos=0
    while pos<len(raw):
        end=pos+1
        while end<len(raw) and raw[end]==raw[pos] and end-pos<65535:end+=1
        packed+=struct.pack('<HB',end-pos,raw[pos]);pos=end
    header+=['static const unsigned char art_'+name+'_data[] = {',
             ','.join(str(x) for x in packed)+'};',
             'static const struct menu_art art_'+name+' = {'+f'{image.width},{image.height},art_{name}_data,sizeof(art_{name}_data)'+'};']
# Use the maintained flat Tux drawing with its original proportions and explicit
# flat-color regions. RGB preserves its white belly and yellow beak/feet.
png=subprocess.check_output(['rsvg-convert','-h','246',str(OUT/'tux-standard-flat-color.svg')])
image=Image.open(io.BytesIO(png)).convert('RGBA')
pixels=list(image.getdata());packed=bytearray();pos=0
while pos<len(pixels):
    end=pos+1
    while end<len(pixels) and pixels[end]==pixels[pos] and end-pos<65535:end+=1
    packed+=struct.pack('<H4B',end-pos,*pixels[pos]);pos=end
header+=['struct menu_color_art { int w,h; const unsigned char *data; unsigned int bytes; };',
         'static const unsigned char art_tux_data[] = {',','.join(str(x) for x in packed)+'};',
         'static const struct menu_color_art art_tux = {'+f'{image.width},{image.height},art_tux_data,sizeof(art_tux_data)'+'};']
(OUT/'menu-art.h').write_text('\n'.join(header)+'\n')
print('Menu masks:',sum(len(x.tobytes()) for x in assets.values()),'alpha bytes; header', (OUT/'menu-art.h').stat().st_size)
